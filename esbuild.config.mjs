// TimeNote 构建配置：main.ts -> main.js
// 官方 Obsidian 插件同款链路：esbuild 打 CJS 包，obsidian/electron 等保持 external。
import esbuild from "esbuild";
import process from "process";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD.
Source: main.ts — 请勿直接编辑本文件，改动后执行 npm run build 重新生成。
*/`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  entryPoints: ["main.ts"],
  outfile: "main.js",
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: "es2018",
  external: ["obsidian", "electron", "node:*", "@codemirror/*", "@lezer/*"],
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  // 产物需入库供零构建安装，保持可读便于 diff / 审计；发布时可按需开启压缩
  minify: false,
  banner: { js: banner }
});

if (prod) {
  await context.rebuild();
  await context.dispose();
} else {
  console.log("esbuild watch mode — Ctrl+C 退出");
  await context.watch();
}
